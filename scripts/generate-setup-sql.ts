/**
 * Generates the files you paste into the Supabase SQL editor:
 *   supabase/setup/01_schema.sql         all migrations, in order
 *   supabase/setup/02_dlbts_kn_2026.sql  groups, events, criteria, admin + judge accounts, assignments
 *   docs/JUDGE_LOGINS.md                 printable list of judge usernames (no passwords)
 *
 *   npm run setup:sql
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { groups, JUDGES_PER_EVENT, SCORE_PRECISION, username } from './dlbts-kn-2026.ts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
mkdirSync('supabase/setup', { recursive: true });
mkdirSync('docs', { recursive: true });

// 1. Schema
const files = readdirSync('supabase/migrations')
	.filter((f) => /^\d+_.+\.sql$/.test(f))
	.sort();
let schema = `-- DLBTS KN: complete database schema.\n-- Generated by \`npm run setup:sql\` from supabase/migrations (${files.length} files). Do not edit by hand.\n-- Paste into Supabase -> SQL Editor -> New query, and Run. Run it once, on an empty project.\n\n`;
for (const f of files)
	schema += `\n-- ==================== ${f} ====================\n\n${readFileSync(`supabase/migrations/${f}`, 'utf8')}\n`;
writeFileSync('supabase/setup/01_schema.sql', schema);

// 2. Data
let sql = `-- DLBTS KN 2026: groups, events, criteria, accounts and judge assignments.
-- Generated by \`npm run setup:sql\` from scripts/dlbts-kn-2026.ts. Safe to run again:
-- existing groups/events/accounts are kept (names are updated), nothing is deleted.
--
-- BEFORE RUNNING: change the admin password on the line marked  <<< CHANGE THIS
--
-- Judge usernames: judge<NN><group><event>   e.g. judge01grp2slokagirls
-- Judge passwords: same, with "judge" replaced by "pwd"   e.g. pwd01grp2slokagirls

do $setup$
declare
  v_admin_password text := 'CHANGE-ME';   -- <<< CHANGE THIS (at least 8 characters)
  v_admin uuid;
  v_group uuid;
  v_event uuid;
  v_judge uuid;
  v_user text;
begin
  if v_admin_password = 'CHANGE-ME' or char_length(v_admin_password) < 8 then
    raise exception 'Please set v_admin_password at the top of this script (at least 8 characters).';
  end if;

  v_admin := public.create_account('admin', v_admin_password, 'DLBTS Admin', 'admin');
`;
groups.forEach((g, gi) => {
	sql += `\n  -- ${'='.repeat(60)}\n  -- ${g.name}\n  insert into public.groups (code, name, display_order) values (${q(g.code)}, ${q(g.name)}, ${gi + 1})\n    on conflict (code) do update set name = excluded.name returning id into v_group;\n`;
	g.events.forEach((e, ei) => {
		sql += `\n  -- ${g.name} / ${e.name}\n  insert into public.events (group_id, code, name, description, score_precision, display_order)\n    values (v_group, ${q(e.code)}, ${q(e.name)}, ${q(e.note)}, ${SCORE_PRECISION}, ${ei + 1})\n    on conflict (group_id, code) do update set name = excluded.name, description = excluded.description\n    returning id into v_event;\n`;
		sql += `  if not exists (select 1 from public.evaluation_criteria where event_id = v_event) then\n    insert into public.evaluation_criteria (event_id, name, max_marks, display_order) values\n`;
		sql +=
			e.criteria.map(([n, m], i) => `      (v_event, ${q(n)}, ${m}, ${i + 1})`).join(',\n') +
			';\n  end if;\n';
		for (let nn = 1; nn <= JUDGES_PER_EVENT; nn++) {
			const u = username(nn, g, e);
			sql += `  v_user := ${q(u)};\n  v_judge := public.create_account(v_user, replace(v_user, 'judge', 'pwd'), ${q(`Judge ${nn} · ${g.name} · ${e.name}`)}, 'judge');\n  insert into public.judge_assignments (event_id, judge_id, created_by) values (v_event, v_judge, v_admin)\n    on conflict (event_id, judge_id) do nothing;\n`;
		}
	});
});
sql += `\n  raise notice 'DLBTS KN 2026 setup complete';\nend\n$setup$;\n\n-- Check: one row per event with its judges\nselect g.name as "group", e.name as event, count(a.*) as judges\nfrom public.events e join public.groups g on g.id = e.group_id\nleft join public.judge_assignments a on a.event_id = e.id and a.is_active\ngroup by g.display_order, g.name, e.display_order, e.name order by g.display_order, e.display_order;\n`;
writeFileSync('supabase/setup/02_dlbts_kn_2026.sql', sql);

// 3. Printable login list (no passwords)
let md = `# DLBTS KN 2026 – judge logins\n\nGenerated by \`npm run setup:sql\`. **Password rule:** replace \`judge\` with \`pwd\` in the username\n(e.g. \`judge01grp2slokagirls\` → \`pwd01grp2slokagirls\`). Admins can set a different password\nfor anyone under **Judges**.\n`;
let total = 0;
for (const g of groups) {
	md += `\n## ${g.name}\n\n| Event | Who | Judge 1 | Judge 2 |\n|---|---|---|---|\n`;
	for (const e of g.events) {
		md += `| ${e.name} | ${e.note} | \`${username(1, g, e)}\` | \`${username(2, g, e)}\` |\n`;
		total += JUDGES_PER_EVENT;
	}
}
md += `\nTotal: ${groups.reduce((s, g) => s + g.events.length, 0)} events, ${total} judge accounts.\n`;
writeFileSync('docs/JUDGE_LOGINS.md', md);

console.log(
	`Wrote supabase/setup/01_schema.sql (${files.length} migrations), 02_dlbts_kn_2026.sql, docs/JUDGE_LOGINS.md (${total} judges).`
);
